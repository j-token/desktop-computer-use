/// The keysym for `name`, or 0 (NoSymbol). Like XStringToKeysym, a name that
/// is no keysym name but a 0x-prefixed hexadecimal number is that number.
pub fn keysym_from_name(name: &str) -> u32 {
    if let Ok(index) =
        LOWERCASE_KEYSYM_NAMES.binary_search_by(|(candidate, _)| (*candidate).cmp(name))
    {
        return LOWERCASE_KEYSYM_NAMES[index].1;
    }
    match name.strip_prefix("0x") {
        Some(digits) if !digits.is_empty() => u32::from_str_radix(digits, 16).unwrap_or(0),
        _ => 0,
    }
}
