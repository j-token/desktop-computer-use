// Writes native/THIRD_PARTY_LICENSES.md from the crates linked into the
// shipped desktop-computer-use-native executables. `--check` fails instead of
// writing when the committed report no longer matches Cargo.lock.
import { execFile } from "node:child_process";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const report = join(root, "native", "THIRD_PARTY_LICENSES.md");
const executablePackage = "desktop-computer-use-native";
const shippedTargets = ["x86_64-pc-windows-msvc", "x86_64-unknown-linux-gnu"];
const licenseFileName = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

async function cargoMetadata(target) {
  const { stdout } = await promisify(execFile)(
    "cargo",
    ["metadata", "--format-version", "1", "--locked", "--filter-platform", target],
    { cwd: root, maxBuffer: 64 * 1024 * 1024, windowsHide: true }
  );
  return JSON.parse(stdout);
}

// Build scripts and proc macros run on the build machine only, so the walk
// follows normal dependencies, the ones compiled into the executable.
function linkedPackages(metadata) {
  const nodes = new Map(metadata.resolve.nodes.map(node => [node.id, node]));
  const rootId = metadata.packages.find(item => item.name === executablePackage).id;
  const linked = new Set();
  const pending = [rootId];
  while (pending.length > 0) {
    const id = pending.pop();
    if (linked.has(id)) continue;
    linked.add(id);
    for (const dependency of nodes.get(id).deps) {
      if (dependency.dep_kinds.some(kind => kind.kind === null)) pending.push(dependency.pkg);
    }
  }
  return metadata.packages.filter(item => linked.has(item.id) && item.source !== null);
}

async function licenseTexts(item) {
  const directory = dirname(item.manifest_path);
  const names = (await readdir(directory)).filter(name => licenseFileName.test(name)).sort();
  if (item.license_file && !names.includes(item.license_file)) names.push(item.license_file);
  return Promise.all(names.map(async name => ({
    name,
    text: (await readFile(join(directory, name), "utf8")).replaceAll("\r\n", "\n").trimEnd()
  })));
}

const packages = new Map();
for (const target of shippedTargets) {
  for (const item of linkedPackages(await cargoMetadata(target))) {
    const entry = packages.get(item.id) ?? { item, targets: [] };
    entry.targets.push(target);
    packages.set(item.id, entry);
  }
}
const sorted = [...packages.values()].sort((left, right) =>
  left.item.name.localeCompare(right.item.name) || left.item.version.localeCompare(right.item.version));

const lines = [
  "# Native dependency licenses",
  "",
  "This file is generated by `node scripts/native-licenses.mjs` from `Cargo.lock`. It lists every crate " +
    "compiled into the `desktop-computer-use-native` executables, the targets that link it, and the license " +
    "files the crate ships.",
  ""
];
for (const { item, targets } of sorted) {
  lines.push(`## ${item.name}@${item.version}`, "", `License: ${item.license ?? "unspecified"}`, "");
  lines.push(`Targets: ${targets.join(", ")}`, "");
  const texts = await licenseTexts(item);
  if (texts.length === 0) {
    lines.push("The crate does not ship a standalone license file.", "");
  }
  for (const { name, text } of texts) {
    lines.push(`### ${name}`, "", "```text", text, "```", "");
  }
}
const generated = `${lines.join("\n").trimEnd()}\n`;

if (process.argv.includes("--check")) {
  const committed = await readFile(report, "utf8").catch(() => "");
  if (committed.replaceAll("\r\n", "\n") !== generated) {
    console.error("native/THIRD_PARTY_LICENSES.md is stale; run `node scripts/native-licenses.mjs`.");
    process.exit(1);
  }
} else {
  await writeFile(report, generated, "utf8");
  console.log(`Wrote ${packages.size} crate licenses to ${report}`);
}
